    /** How much of a fun story [sentence] tells: 0 means leave it out, [PASS] or more means show it */
    fun score(sentence: String): Int {
        val s = sentence.trim()
        if (s.length !in MIN_LENGTH..MAX_LENGTH) return 0
        if (s.startsWith("\"") || s.startsWith("“")) return 0
        if (BAD_STARTS.any { s.startsWith("$it ") || s.startsWith("$it,") }) return 0
        if (FIRST_PERSON.containsMatchIn(s)) return 0
        if (DULL.any { it.containsMatchIn(s) } || UNSAFE.any { it.containsMatchIn(s) }) return 0
        return 2 * STRONG.count { it.containsMatchIn(s) } + WEAK.count { it.containsMatchIn(s) }
    }

    /** True when [fact] (maybe starting with "Title: ") is still fun by today's rules */
    fun isFun(
        fact: String,
        title: String? = null,
    ): Boolean {
        val text = if (title != null && fact.startsWith("$title: ")) fact.removePrefix("$title: ") else fact
        return score(text) >= PASS
    }
